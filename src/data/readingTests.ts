  id: string;
  number: number;
  title: string;
  mode: ReadingMode;
  topicSummary: string;
  difficulty: 'Standard' | 'Upper-Intermediate' | 'Advanced';
  durationMinutes: number;
  isPremium: boolean;
  passages: [ReadingPassage, ReadingPassage, ReadingPassage];
